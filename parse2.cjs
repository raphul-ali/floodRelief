const sqlStmts = [];
sqlStmts.push('INSERT INTO victim_requests (id, created_at, name, phone, alt_phone, people_count, district, village_name, latitude, longitude, is_urgent_rescue, needs, details, status, ground_condition, urgency, verified, verified_at) VALUES');

const values = parsed.filter(item => {
    // Only include items where boat_required is FALSE or falsy. 
    // They said "add only for relief dont add anything to rescue"
    return !item.boat_required;
}).map(item => {
    // Map fields safely
    const escapeStr = (s) => typeof s === 'string' ? "'" + s.replace(/'/g, "''") + "'" : 'NULL';
    
    const id = escapeStr(item.id);
    const created_at = escapeStr(item.created_at);
    const name = escapeStr(item.name);
    const phone = escapeStr(item.contact_number);
    const alt_phone = (item.contact_numbers && item.contact_numbers.length > 0) ? escapeStr(item.contact_numbers[0]) : 'NULL';
    
    const people_count = item.num_people || 0;
    const district = escapeStr(item.district);
    const village_name = escapeStr(item.location);
    
    const lat = item.lat !== null ? item.lat : (item.live_lat !== null ? item.live_lat : 'NULL');
    const lng = item.lng !== null ? item.lng : (item.live_lng !== null ? item.live_lng : 'NULL');
    
    // Always false since we filtered them
    const is_urgent_rescue = 'FALSE';
    
    const needsArr = item.needs || [];
    if (item.needs_other) needsArr.push(item.needs_other);
    const needsJson = needsArr.length > 0 ? escapeStr(JSON.stringify(needsArr)) : "NULL";
    
    const details = escapeStr(item.notes);
    const status = escapeStr(item.status || 'PENDING');
    
    let urgency = 'HIGH';
    if (item.priority === 'needed') urgency = 'MEDIUM';
    else if (item.priority === 'low') urgency = 'LOW';
    
    // ground_condition for relief
    const ground_condition = 'RECEDING';
    
    return `(${id}, ${created_at}, ${name}, ${phone}, ${alt_phone}, ${people_count}, ${district}, ${village_name}, ${lat}, ${lng}, ${is_urgent_rescue}, ${needsJson}, ${details}, ${status}, '${ground_condition}', '${urgency}', TRUE, NOW())`;
});

